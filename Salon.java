public class Salon {
    int id;
    String name;
    String location;
    int noOfStaff;
    int establishedYear;

    Salon(int id, String name, String location, int noOfStaff, int establishedYear) {
        this.id = id;
        this.name = name;
        this.location = location;
        this.noOfStaff = noOfStaff;
        this.establishedYear = establishedYear;
    }
}
