public class FastTag {
    int id;
    String vehicleNumber;
    String ownerName;
    double balance;
    String bankName;

    FastTag(int id, String vehicleNumber, String ownerName, double balance, String bankName) {
        this.id = id;
        this.vehicleNumber = vehicleNumber;
        this.ownerName = ownerName;
        this.balance = balance;
        this.bankName = bankName;
    }
}