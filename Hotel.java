public class Hotel {
    int id;
    String name;
    String location;
    int noOfRooms;
    int starRating;

    Hotel(int id, String name, String location, int noOfRooms, int starRating) {
        this.id = id;
        this.name = name;
        this.location = location;
        this.noOfRooms = noOfRooms;
        this.starRating = starRating;
    }
}