public class Specs {
    int id;
    String brand;
    String frameMaterial;
    String lensType;
    double price;

    Specs(int id, String brand, String frameMaterial, String lensType, double price) {
        this.id = id;
        this.brand = brand;
        this.frameMaterial = frameMaterial;
        this.lensType = lensType;
        this.price = price;
    }
}

