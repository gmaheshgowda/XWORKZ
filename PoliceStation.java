public class PoliceStation {
    int id;
    String name;
    String location;
    int noOfOfficers;
    int establishedYear;

    PoliceStation(int id, String name, String location, int noOfOfficers, int establishedYear) {
        this.id = id;
        this.name = name;
        this.location = location;
        this.noOfOfficers = noOfOfficers;
        this.establishedYear = establishedYear;
    }
}
