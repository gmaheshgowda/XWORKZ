public class Apartment {
    int id;
    String name;
    String address;
    int noOfBlocks;
    int noOfFlats;

    Apartment(int id, String name, String address, int noOfBlocks, int noOfFlats) {
        this.id = id;
        this.name = name;
        this.address = address;
        this.noOfBlocks = noOfBlocks;
        this.noOfFlats = noOfFlats;
    }
}
