public class Sports {
    int id;
    String name;
    int noOfPlayers;
    int noOfRules;
    String countryOfOrigin;

    Sports(int id, String name, int noOfPlayers, int noOfRules, String countryOfOrigin) {
        this.id = id;
        this.name = name;
        this.noOfPlayers = noOfPlayers;
        this.noOfRules = noOfRules;
        this.countryOfOrigin = countryOfOrigin;
    }
}
