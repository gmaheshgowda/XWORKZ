public class Library {
    String name;
    String location;
    int noOfBooks;
    int establishedYear;
    int noOfStaff;

    Library(String name, String location, int noOfBooks, int establishedYear, int noOfStaff) {
        this.name = name;
        this.location = location;
        this.noOfBooks = noOfBooks;
        this.establishedYear = establishedYear;
        this.noOfStaff = noOfStaff;
    }
}