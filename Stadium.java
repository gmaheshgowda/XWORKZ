public class Stadium {
    int id;
    String name;
    String teamName;
    String state;
    int capacity;
    double area;

    Stadium(int id, String name, String teamName, String state, int capacity, double area) {
        this.id = id;
        this.name = name;
        this.teamName = teamName;
        this.state = state;
        this.capacity = capacity;
        this.area = area;
    }
}

